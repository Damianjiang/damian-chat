/**
 * lib/i18n.ts —— 轻量全站国际化。
 *
 * 设计原则（保证「没有任何问题」）：
 *  1. 未知 key 一律回退中文（dict.zh），翻译漏了也不会出现 key 字符串；
 *  2. 组件直接 import { t } 使用（t 读 Pinia language store，响应式切换）；
 *  3. 支持简单参数插值：t('pat', { a: 'A', b: 'B' }) → 「A 拍了拍 B」/ "A patted B"。
 *  4. 用户内容（昵称、消息、群名）不走 t，保持原样。
 */
import { useLanguageStore } from '@/stores/language'

export type Lang = 'zh' | 'en'

/** 取当前语言下的文案。key 缺失时回退中文，再缺失回退 key 本身。 */
export function t (key: string, params?: Record<string, string | number>): string {
  const lang = useLanguageStore().lang
  let s: string
  if (lang === 'en' && dict.en[key]) s = dict.en[key]
  else s = dict.zh[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v))
    }
  }
  return s
}

