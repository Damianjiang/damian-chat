/**
 * 渲染单个 MDI 图标为内联 SVG（fill: currentColor），作为 Vuetify icons.sets['mdi'].component。
 *
 * Vuetify useIcon 已把「$alias」解析成「mdi-*」名再传入，这里只需查 mdiIconPaths。
 * 未知图标 → 渲染空 <i>（不产生黑块，并 console.warn 便于排查）。
 *
 * class / style 不在 props 里声明 —— 它们是 Vue 的 fallthrough 属性，会经 $attrs 落到根节点；
 * 显式声明成 prop 反而会拦截掉 Vuetify 透传下来的 v-icon 尺寸/主题/颜色类名。
 */
export const MdiSvgIcon = defineComponent({
  name: 'MdiSvgIcon',
  inheritAttrs: false,
  props: {
    icon: { type: [String, Array], required: true } as any,
    tag: { type: [String, Object] as any, default: 'i' },
  },
  setup (props, { attrs }) {
    return () => {
      // 兼容数组图标（取第一个）与前后缀差异
      const iconName = Array.isArray(props.icon)
        ? String((props.icon as unknown[])[0] ?? '')
        : String(props.icon ?? '')
      const path = mdiIconPaths[iconName] ?? mdiIconPaths[iconName.replace(/^mdi-/, '')]

      if (!path) {
        console.warn(`[mdi-svg] 未知图标：${iconName}（未纳入 @mdi/js 映射表，请补导入）`)
        return h(props.tag, { class: ['v-icon', ...(attrs.class ? [attrs.class] : [])], style: attrs.style })
      }

      // 根节点用 Vuetify 期望的 <i>（带 v-icon 类以保留尺寸/主题/颜色类名），
      // 内部 <svg> 以 1em 跟随 font-size，fill:currentColor 继承文字/按钮颜色。
      const cls = attrs.class
      return h(props.tag, {
        class: ['v-icon', ...(cls ? [cls] : [])],
        style: attrs.style,
        onClick: attrs.onClick,
      }, [
        h('svg', {
          class: 'v-icon__mdi',
          xmlns: 'http://www.w3.org/2000/svg',
          viewBox: '0 0 24 24',
          fill: 'currentColor',
          'aria-hidden': 'true',
          style: 'display:block;width:1em;height:1em;overflow:visible',
        }, [h('path', { d: path })]),
      ])
    }
  },
})
