/**
 * lib/mdi-svg.ts
 *
 * MDI 图标 → 内联 SVG（fill: currentColor）
 *
 * 原因：原方案用 @mdi/font webfont（PUA 私有区字形 ::before）。
 * 在旧手机 / 旧电脑上，webfont 的 403KB woff2 经常没真正应用，
 * PUA 码点回退成系统 CJK 字体 → 实心黑方块（tofu）。
 * 换成 SVG 后：
 *   • 无 PUA 码点，永不黑块
 *   • fill: currentColor，灰按钮上图标颜色自动继承（不黑）
 *   • 省掉 3.6MB webfont 下载（403K woff2 + 588K woff + 1.3M ttf + 1.3M eot）
 */
