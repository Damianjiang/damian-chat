using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace WeChatWeb.Services;

/// <summary>
/// 安全配置（注册密钥 / 验证码开关 / 登录锁定策略）。
/// 内存单例 + security.json 持久化：WxAdmin 后台可改（服务运行中走管理 API，停止时直接改文件），重启或热更新均生效。
/// </summary>
public sealed class SecuritySettings
{
    /// <summary>注册密码（用户注册时必须填写）。为空表示关闭注册，可在管理端设置。</summary>
    public string RegisterKey { get; set; } = "";
    public bool EnableCaptcha { get; set; } = true;
    /// <summary>滑块验证开关（登录/注册按钮点击即弹出）。管理端可关；关闭后仅剩图形验证码防线。</summary>
    public bool EnableSlider { get; set; } = true;
    public int MaxLoginAttempts { get; set; } = 5;
    public int LockoutMinutes { get; set; } = 10;
    public int AuthPerMinute { get; set; } = 20;
    public int ApiPerMinute { get; set; } = 300;

    // ============ 流量防火墙（全站，挂在中间件管线最前） ============
    /// <summary>每 IP 每分钟全站请求数上限（所有路径：静态/SPA//files//api//hubs 都算）。正常用户/多标签页/刷新远远达不到 1000。</summary>
    public int FwRequestsPerMinute { get; set; } = 1000;
    /// <summary>每 IP 并发连接数上限。正常用户同时开几个标签页也就个位数；刷流量的代理池一下就顶到几千。</summary>
    public int FwMaxConcurrent { get; set; } = 60;
    /// <summary>每 IP 每分钟响应下行流量上限（字节）。默认 500MB，防下载型 DDoS 把带宽吃光。正常下载几张朋友圈图/文件远达不到。</summary>
    public long FwBytesPerMinute { get; set; } = 500L * 1024 * 1024;
    /// <summary>触发封禁的阈值：1 分钟内累计 429 次数达到该值即封。</summary>
    public int FwBanThreshold { get; set; } = 50;
    /// <summary>封禁时长（分钟）。被自动封禁的 IP 在窗口内所有请求直接 429 + Retry-After。</summary>
    public int FwBanMinutes { get; set; } = 30;

    // ============ 用户身份（JWT sub）维度消息洪泛上限 ============
    /// <summary>
    /// 同一用户 1 分钟内最多能发多少条消息（POST /api/messages）。
    /// 真人在群里高强度聊天也很少超过 30~50 条/分钟；被偷 token / 自动化脚本 /
    /// 绕过人机验证的重放洪水一打就是几百上千条。默认 60（约 1 条/秒，真人几乎达不到），
    /// 攻击者远超阈值即 429。设 0 或负值 = 关闭此上限（钳制到 1）。
    /// ★ 这是**身份维度**（JWT sub），跟 IP 防火墙互补：轮换 IP 池 / 偷单一 token 重放也躲不掉。
    /// </summary>
    public int FloodMessagesPerMinute { get; set; } = 60;

    // ============ 注册模式（微信式账号体系） ============
    /// <summary>
    /// 注册方式："direct"（账号+密码，大面号=注册账号）/"email"（邮箱+验证码，大面号随机生成
    /// 且默认不可被搜索——与微信 2017 年后关闭随机 wxid 搜索一致，改成自定义大面号后才可被搜到）。
    /// </summary>
    public string RegisterMode { get; set; } = "direct";

    /// <summary>大面号修改冷却天数（微信为 365 天一次）。0 = 不限次数。</summary>
    public int WxIdChangeCooldownDays { get; set; } = 365;

    // ============ SMTP（邮箱注册验证码 / 绑定邮箱） ============
    public string SmtpHost { get; set; } = "";
    public int SmtpPort { get; set; } = 465;
    public string SmtpUser { get; set; } = "";
    /// <summary>SMTP 密码/授权码。落盘在 security.json（与注册密钥同级的敏感配置）。</summary>
    public string SmtpPass { get; set; } = "";
    /// <summary>发件人地址；留空则用 SmtpUser。</summary>
    public string SmtpFrom { get; set; } = "";
    /// <summary>true = SSL/TLS 直连（465），false = STARTTLS（587）。</summary>
    public bool SmtpSsl { get; set; } = true;

    /// <summary>SMTP 是否已配置完整（发验证码的前置条件）。</summary>
    public bool SmtpReady => !string.IsNullOrWhiteSpace(SmtpHost) && !string.IsNullOrWhiteSpace(SmtpUser) && !string.IsNullOrWhiteSpace(SmtpPass);

    /// <summary>本次启动是否自动生成/轮换了注册密钥（供启动日志提示管理员查看新密钥）。</summary>
    public bool RegisterKeyAutoGenerated { get; private set; }

    private static readonly JsonSerializerOptions JsonOpts = new() { WriteIndented = true, DefaultIgnoreCondition = JsonIgnoreCondition.Never };

    /// <summary>security.json 路径：环境变量 WX_SECURITY_FILE 优先，默认当前工作目录（server/WeChatWeb）。</summary>
    public static string FilePath =>
        Environment.GetEnvironmentVariable("WX_SECURITY_FILE")
        ?? Path.Combine(Directory.GetCurrentDirectory(), "security.json");

    /// <summary>
    /// 既往版本文档/代码里出现过的注册密钥（等同公开）。启动时检测到一律自动轮换，
    /// 防止部署到互联网后攻击者按文档默认值直接注册。
    /// </summary>
    private static readonly string[] KnownCompromisedKeys = { "newregpass888", "wx2026" };

    public static SecuritySettings Load ()
    {
        try
        {
            if (File.Exists(FilePath))
            {
                // 自愈读：存在但读不到（历史遗留空 DACL）时先修 ACL 再读，
                // 否则会静默重新生成注册密钥，把管理员设过的值悄悄换掉。
                if (!SensitiveFile.TryReadAllText(FilePath, out var raw))
                {
                    Console.Error.WriteLine(
                        $"[安全] 警告：无法读取 {FilePath}，将使用新生成的注册密钥。" +
                        "请修复该文件权限（见上方 [敏感文件权限] 提示）后重启。");
                }
                else
                {
                var s = JsonSerializer.Deserialize<SecuritySettings>(raw);
                if (s != null)
                {
                    // 已知公开默认值 → 自动轮换（管理员可在管理端改回自定义值）
                    if (KnownCompromisedKeys.Contains(s.RegisterKey))
                    {
                        s.RegisterKey = GenerateRegisterKey();
                        s.RegisterKeyAutoGenerated = true;
                        Console.WriteLine("[安全] 检测到公开的默认注册密钥，已自动轮换。新密钥见管理端「安全设置」或启动日志。");
                    }
                    s.Normalized();
                    if (s.RegisterKeyAutoGenerated) s.Save();
                    return s;
                }
                }
            }
            else
            {
                // 首次启动：自动生成随机注册密钥（开放注册但密钥未知），并在启动日志中提示
                var def = new SecuritySettings
                {
                    RegisterKey = GenerateRegisterKey(),
                    RegisterKeyAutoGenerated = true,
                };
                Console.WriteLine("[安全] 已自动生成随机注册密钥（开放注册）。查看/修改：管理端「安全设置」，或 data 日志目录。");
                def.Save();
                return def;
            }
        }
        catch
        {
            // 文件损坏时回退默认
        }
        var fallback = new SecuritySettings
        {
            RegisterKey = GenerateRegisterKey(),
            RegisterKeyAutoGenerated = true,
        };
        fallback.Save();
        return fallback;
    }

    /// <summary>生成 12 位无歧义随机注册密钥（去掉 0/O/1/I/l）。</summary>
    public static string GenerateRegisterKey ()
    {
        const string alphabet = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789";
        var chars = new char[12];
        for (var i = 0; i < chars.Length; i++)
            chars[i] = alphabet[RandomNumberGenerator.GetInt32(alphabet.Length)];
        return new string(chars);
    }

    public void Save ()
    {
        try
        {
            File.WriteAllText(FilePath, JsonSerializer.Serialize(this, JsonOpts));
            SensitiveFile.RestrictToOwner(FilePath);
        }
        catch
        {
            // 只读环境下仅内存生效
        }
    }

    private SecuritySettings Normalized ()
    {
        if (MaxLoginAttempts < 1) MaxLoginAttempts = 5;
        if (LockoutMinutes < 1) LockoutMinutes = 10;
        if (AuthPerMinute < 1) AuthPerMinute = 20;
        if (ApiPerMinute < 10) ApiPerMinute = 300;
        // 防火墙下限钳制：防止管理员误填 0/负值导致整站不可用
        if (FwRequestsPerMinute < 100) FwRequestsPerMinute = 100;
        if (FwMaxConcurrent < 2) FwMaxConcurrent = 2;
        if (FwBytesPerMinute < 1L * 1024 * 1024) FwBytesPerMinute = 1L * 1024 * 1024; // 至少 1MB
        // 封禁阈值下限抬到 50：浏览器同 IP 开多标签/SPA 并行拉资源会在瞬时超过 20 并发，
        // 旧阈值 5 会让「正常用户」被误判成刷流量而 auto-ban 30 分钟（firewall.jsonl 有铁证）。
        // 设 ≥10 才允许自定义，否则钳到 50（防误填 1~9 秒杀正常用户）。
        if (FwBanThreshold < 10) FwBanThreshold = 50;
        if (FwBanMinutes < 1) FwBanMinutes = 30;
        // 用户消息洪泛上限：下限钳 1（0/负 = 关闭），上限钳 100000 防误填炸库
        if (FloodMessagesPerMinute < 1) FloodMessagesPerMinute = 1;
        if (FloodMessagesPerMinute > 100000) FloodMessagesPerMinute = 100000;
        return this;
    }

    /// <summary>注册密码强度：空 = 关闭注册；非空时至少 8 位（后端与控制台共同约束）。</summary>
    public const int MinRegisterKeyLength = 8;

    /// <summary>注册密码恒定时间比较（防时序侧信道）。RegisterKey 为空表示注册关闭。</summary>
    public bool RegisterKeyMatches (string? input)
    {
        if (string.IsNullOrEmpty(RegisterKey)) return false;
        if (string.IsNullOrEmpty(input)) return false;
        var a = System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(RegisterKey));
        var b = System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(input));
        return System.Security.Cryptography.CryptographicOperations.FixedTimeEquals(a, b);
    }
}
